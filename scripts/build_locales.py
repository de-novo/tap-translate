def extra_for(locale: str) -> dict[str, str]:
    return {key: translations.get(locale, translations["en"]) for key, translations in EXTRA.items()}


def to_messages(locale_strings: dict[str, str]) -> dict:
    messages = {}
    for key, message in locale_strings.items():
        entry = {"message": message}
        if key in PLACEHOLDERS:
            entry["placeholders"] = PLACEHOLDERS[key]
        messages[key] = entry
    return messages


def main() -> None:
    expected = set(STRINGS["en"]) | set(EXTRA)
    for locale, strings in STRINGS.items():
        strings = {**strings, **extra_for(locale)}
        missing = expected - set(strings)
        extra = set(strings) - expected
        if missing or extra:
            raise SystemExit(f"{locale}: missing={sorted(missing)} extra={sorted(extra)}")
        dest = LOCALES / locale / "messages.json"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(
            json.dumps(to_messages(strings), ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        print(f"wrote {dest.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
